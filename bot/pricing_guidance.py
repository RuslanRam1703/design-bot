def percent_to_stored(kind: str, key: str, value: float) -> float:
    if not math.isfinite(value) or value < 0:
        raise ValueError("Введите неотрицательное число.")
    if key == 'round_to':
        if value < 1 or value != int(value):
            raise ValueError("Шаг округления — целое число рублей, не меньше 1.")
        return value
    if kind == 'round' and key == 'price_from_factor':
        if value >= 100:
            raise ValueError("Уменьшение нижней границы должно быть меньше 100%.")
        return 1 - value / 100
    return 1 + value / 100


